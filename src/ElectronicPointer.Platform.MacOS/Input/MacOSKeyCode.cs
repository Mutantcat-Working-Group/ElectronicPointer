        0x2F => KeyCode.Period,
        0x32 => KeyCode.None,
        0x30 => KeyCode.Tab,
        0x31 => KeyCode.Space,
        0x33 => KeyCode.Delete,
        0x35 => KeyCode.Escape,
        0x41 => KeyCode.None,
        0x43 => KeyCode.None,
        0x45 => KeyCode.None,
        0x4B => KeyCode.None,
        0x4C => KeyCode.None,
        0x4E => KeyCode.None,
        0x51 => KeyCode.None,
        0x52 => KeyCode.NumPad0,
