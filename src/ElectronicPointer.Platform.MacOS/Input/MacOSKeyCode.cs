using Mutantcat.ElectronicPointer.Core.Input;

namespace Mutantcat.ElectronicPointer.Platform.MacOS;

/// <summary>
/// macOS virtual key codes as reported by <c>kCGKeyboardEventKeycode</c>, mapped onto the
/// platform-neutral key set. The table uses the ANSI (US) layout constants that CoreGraphics
/// reports regardless of the active input method, which is what keeps a binding made in one
/// keyboard layout meaningful on another machine. Anything outside the table reports
/// <see cref="KeyCode.None"/>, so a codec we do not know cannot silently bind to something else.
/// </summary>
internal static class MacOSKeyCode
{
    public static KeyCode FromVirtualKeyCode(int code) => code switch
    {
        0x00 => KeyCode.A,
        0x01 => KeyCode.S,
        0x02 => KeyCode.D,
        0x03 => KeyCode.F,
        0x04 => KeyCode.H,
        0x05 => KeyCode.G,
        0x06 => KeyCode.Z,
        0x07 => KeyCode.X,
        0x08 => KeyCode.C,
        0x09 => KeyCode.V,
        0x0B => KeyCode.B,
        0x0C => KeyCode.Q,
        0x0D => KeyCode.W,
        0x0E => KeyCode.E,
        0x0F => KeyCode.R,
        0x10 => KeyCode.Y,
        0x11 => KeyCode.T,
        0x12 => KeyCode.D1,
        0x13 => KeyCode.D2,
        0x14 => KeyCode.D3,
        0x15 => KeyCode.D4,
        0x16 => KeyCode.D6,
        0x17 => KeyCode.D5,
        0x18 => KeyCode.Plus,
        0x19 => KeyCode.D9,
        0x1A => KeyCode.D7,
        0x1B => KeyCode.Minus,
        0x1C => KeyCode.D8,
        0x1D => KeyCode.D0,
        0x1E => KeyCode.None,
        0x1F => KeyCode.O,
        0x20 => KeyCode.U,
        0x21 => KeyCode.None,
        0x22 => KeyCode.I,
        0x23 => KeyCode.P,
        0x24 => KeyCode.Enter,
        0x25 => KeyCode.L,
        0x26 => KeyCode.J,
        0x27 => KeyCode.None,
        0x28 => KeyCode.K,
        0x29 => KeyCode.None,
        0x2A => KeyCode.None,
        0x2B => KeyCode.Comma,
        0x2C => KeyCode.None,
        0x2D => KeyCode.N,
