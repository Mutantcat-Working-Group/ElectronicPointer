        0x56 => KeyCode.NumPad4,
        0x57 => KeyCode.NumPad5,
        0x58 => KeyCode.NumPad6,
        0x59 => KeyCode.NumPad7,
        0x5B => KeyCode.NumPad8,
        0x5C => KeyCode.NumPad9,
        0x60 => KeyCode.F5,
        0x61 => KeyCode.F6,
        0x62 => KeyCode.F7,
        0x63 => KeyCode.F3,
        0x64 => KeyCode.F8,
        0x65 => KeyCode.F9,
        0x67 => KeyCode.F11,
        0x69 => KeyCode.None,
        0x6A => KeyCode.None,
        0x6B => KeyCode.None,
        0x6D => KeyCode.F10,
        0x6F => KeyCode.F12,
        0x71 => KeyCode.None,
        0x72 => KeyCode.None,
        0x73 => KeyCode.Home,
        0x74 => KeyCode.PageUp,
        0x75 => KeyCode.Delete,
